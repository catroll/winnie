class PhoneSignal(Base):
    """Ambient readings: notifications, location fixes and installed apps.

    They share one table because they are read as "what happened recently"
    rather than joined on, and because a new kind then needs no migration. The
    payload is kind-specific; ``label`` and ``body`` carry the searchable text.
    """

    __tablename__ = "phone_signals"
    __table_args__ = (
        UniqueConstraint(
            "device_id", "kind", "external_id", name="uq_phone_signals_device_kind_ext"
        ),
        Index("ix_phone_signals_user_kind_time", "user_id", "kind", "occurred_at"),
    )

    id: Mapped[uuid.UUID] = mapped_column(Uuid, primary_key=True, default=uuid.uuid4)
    user_id: Mapped[str] = mapped_column(String(128), index=True)
    device_id: Mapped[uuid.UUID] = mapped_column(
        Uuid, ForeignKey("phone_devices.id", ondelete="CASCADE"), index=True
    )
    kind: Mapped[str] = mapped_column(String(32), index=True)
    external_id: Mapped[str] = mapped_column(String(128))
    occurred_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True, index=True
    )
    label: Mapped[str] = mapped_column(String(512), default="")
    body: Mapped[str] = mapped_column(Text, default="")
    payload: Mapped[dict[str, Any]] = mapped_column(JSON, default=dict)
    deleted_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=utcnow
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=utcnow, onupdate=utcnow
    )


class PhoneCommand(Base):
    """A write the assistant proposes and the phone executes.

    ``proposed`` becomes ``approved`` only after the owner confirms in chat,
    then the phone claims it (``dispatched``) and reports a result. A proposed
    command that is never confirmed expires; it is never executed.
    """

    __tablename__ = "phone_commands"
    __table_args__ = (
        Index("ix_phone_commands_device_status", "device_id", "status"),
    )

    id: Mapped[uuid.UUID] = mapped_column(Uuid, primary_key=True, default=uuid.uuid4)
    user_id: Mapped[str] = mapped_column(String(128), index=True)
    device_id: Mapped[uuid.UUID] = mapped_column(
        Uuid, ForeignKey("phone_devices.id", ondelete="CASCADE"), index=True
    )
    # calendar.create | calendar.update | calendar.delete | sms.send
    kind: Mapped[str] = mapped_column(String(32))
    payload: Mapped[dict[str, Any]] = mapped_column(JSON, default=dict)
    summary: Mapped[str] = mapped_column(Text, default="")
    # proposed | approved | dispatched | succeeded | failed | cancelled | expired
    status: Mapped[str] = mapped_column(String(16), default="proposed", index=True)
    result: Mapped[str] = mapped_column(Text, default="")
    error: Mapped[str] = mapped_column(Text, default="")
    expires_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )
    approved_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )
    dispatched_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )
    completed_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=utcnow
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=utcnow, onupdate=utcnow
    )
