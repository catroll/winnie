"""SQLAlchemy models for synced phone data.

All timestamps are stored as naive UTC. The client sends ISO-8601 with an
offset and the service normalises before writing; readers attach UTC again.
SQLite has no timezone type, so normalising in one place is what keeps the
assistant's date filters correct on both SQLite and PostgreSQL.

Every row belongs to a user and a device. Deletes are soft (``deleted_at``) for
record kinds the phone can delete, because a later full snapshot must not
resurrect them and the assistant must not cite them. Retention eventually
removes the tombstones.
"""

from __future__ import annotations

import uuid
from datetime import datetime, timezone
from typing import Any

from sqlalchemy import (
    JSON,
    Boolean,
    DateTime,
    ForeignKey,
    Index,
    Integer,
    String,
    Text,
    UniqueConstraint,
    Uuid,
)
from sqlalchemy.orm import Mapped, mapped_column

from winnie_core.db import Base


def utcnow() -> datetime:
    return datetime.now(timezone.utc).replace(tzinfo=None)


def as_utc(value: datetime | None) -> datetime | None:
    """Return a naive UTC datetime: aware values are converted, naive assumed UTC."""
    if value is None:
        return None
    if value.tzinfo is None:
        return value
    return value.astimezone(timezone.utc).replace(tzinfo=None)


class PhoneDevice(Base):
    __tablename__ = "phone_devices"
    __table_args__ = (
        UniqueConstraint("user_id", "device_key", name="uq_phone_devices_user_key"),
    )

    id: Mapped[uuid.UUID] = mapped_column(Uuid, primary_key=True, default=uuid.uuid4)
    user_id: Mapped[str] = mapped_column(String(128), index=True)
    # Stable identifier generated by the app; survives a server-side wipe of
    # the device row, so re-registering reuses one device instead of adding a
    # new one every time.
    device_key: Mapped[str] = mapped_column(String(64))
    name: Mapped[str] = mapped_column(String(128), default="")
    platform: Mapped[str] = mapped_column(String(32), default="android")
    manufacturer: Mapped[str] = mapped_column(String(64), default="")
    model: Mapped[str] = mapped_column(String(128), default="")
    os_version: Mapped[str] = mapped_column(String(64), default="")
    app_version: Mapped[str] = mapped_column(String(32), default="")
    timezone: Mapped[str] = mapped_column(String(64), default="")
    # Scopes the phone currently syncs; the server never enables one itself.
    scopes: Mapped[list[str]] = mapped_column(JSON, default=list)
    # Extensible snapshot: battery, storage, network, locale, SIM, accounts.
    info: Mapped[dict[str, Any]] = mapped_column(JSON, default=dict)
    revoked: Mapped[bool] = mapped_column(Boolean, default=False)
    last_seen_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )
    last_sync_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=utcnow
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=utcnow, onupdate=utcnow
    )


